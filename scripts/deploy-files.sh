#!/usr/bin/env bash
# Write .dockerignore and .gcloudignore so the image build uploads only what the Dockerfile copies,
# including the data versions that data/gold/CURRENT and data/global/gold/CURRENT name now.
# Run before every image build (mise run deploy:files); the Dockerfile also fails if they disagree.
set -euo pipefail
cd "$(dirname "$0")/.."
A=$(tr -d '[:space:]' < data/gold/CURRENT)
G=$(tr -d '[:space:]' < data/global/gold/CURRENT)
for v in "data/gold/$A" "data/global/gold/$G"; do
    [ -f "$v/manifest.json" ] || { echo "missing $v/manifest.json" >&2; exit 1; }
done

cat > .dockerignore <<END
# Generated by scripts/deploy-files.sh from gold/CURRENT; do not edit by hand.
# Upload only what the Dockerfile copies.
**
!Dockerfile
!api/Cargo.toml
!api/Cargo.lock
!api/src/**
!web/build/**
!firecal.toml
!global/firecal.toml
!data/gold/CURRENT
!data/gold/$A/**
!data/global/gold/CURRENT
!data/global/gold/$G/**
END

cat > .gcloudignore <<END
# Generated by scripts/deploy-files.sh from gold/CURRENT; do not edit by hand.
# Upload only what the Dockerfile copies. Gitignore rules: a directory must be re-included before
# anything inside it can be.
/*
!/Dockerfile
!/firecal.toml
!/api/
/api/*
!/api/Cargo.toml
!/api/Cargo.lock
!/api/src/
!/web/
/web/*
!/web/build/
!/global/
/global/*
!/global/firecal.toml
!/data/
/data/*
!/data/gold/
/data/gold/*
!/data/gold/CURRENT
!/data/gold/$A/
!/data/global/
/data/global/*
!/data/global/gold/
/data/global/gold/*
!/data/global/gold/CURRENT
!/data/global/gold/$G/
END
echo "deploy files: Argentina $A, global $G"
